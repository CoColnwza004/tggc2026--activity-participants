// Fallback deploy: packs dist/<site>/ into the Worker itself (no separate static-asset upload).
// Use when `wrangler deploy` fails at the asset-upload step (e.g. a proxy rewrites its upload token).
// Trade-off: every page/file request then runs the Worker (counts toward the Workers request quota).
// Usage: node scripts/build.mjs && node scripts/build-embedded.mjs
//        npx wrangler deploy -c participant/wrangler.embed.jsonc  (and staff/wrangler.embed.jsonc)
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const TYPES = {
  ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8",
  ".webmanifest": "application/manifest+json", ".json": "application/json", ".txt": "text/plain; charset=utf-8",
  ".png": "image/png", ".jpg": "image/jpeg", ".webp": "image/webp", ".svg": "image/svg+xml",
};
const BIN = new Set([".png", ".jpg", ".webp"]);

for (const site of ["participant", "staff"]) {
  const dir = join(root, "dist", site);
  const files = {};
  (function walk(d) {
    for (const n of readdirSync(d)) {
      const p = join(d, n);
      if (statSync(p).isDirectory()) { walk(p); continue; }
      const ext = extname(n);
      if (n === "_headers" || !TYPES[ext]) continue;
      const rel = "/" + relative(dir, p).split("\\").join("/");
      files[rel] = { t: TYPES[ext], b: BIN.has(ext) ? readFileSync(p).toString("base64") : readFileSync(p, "utf8"), bin: BIN.has(ext) };
    }
  })(dir);
  const src = `// generated by scripts/build-embedded.mjs — do not edit
import real from "../${site}/worker.js";
const FILES = ${JSON.stringify(files)};
const cache = {};
function bytes(k, f) {
  if (!f.bin) return f.b;
  if (!cache[k]) { const s = atob(f.b); const u = new Uint8Array(s.length); for (let i = 0; i < s.length; i++) u[i] = s.charCodeAt(i); cache[k] = u; }
  return cache[k];
}
const ASSETS = {
  async fetch(req) {
    const url = new URL(req.url);
    let p = decodeURIComponent(url.pathname);
    if (p.endsWith("/")) p += "index.html";
    const f = FILES[p];
    if (!f) return new Response("Not found", { status: 404 });
    const immutable = p.startsWith("/assets/") || p.startsWith("/js/");
    const h = new Headers({
      "content-type": f.t,
      "cache-control": immutable && !p.endsWith("og.jpg") ? "public, max-age=31536000, immutable" : "no-cache",
      "x-content-type-options": "nosniff",
      "referrer-policy": "strict-origin-when-cross-origin",
      "permissions-policy": "camera=(self), microphone=(), geolocation=()",
    });
    ${site === "staff" ? 'h.set("x-robots-tag", "noindex, nofollow");' : ""}
    return new Response(req.method === "HEAD" ? null : bytes(p, f), { headers: h });
  },
};
export default { fetch: (req, env, ctx) => real.fetch(req, { ...env, ASSETS }, ctx) };
`;
  writeFileSync(join(root, "dist", `${site}-embedded.js`), src);
  console.log(`dist/${site}-embedded.js`, Object.keys(files).length, "files,", Math.round(src.length / 1024), "KB");
}
